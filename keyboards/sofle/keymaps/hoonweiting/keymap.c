bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  switch (keycode) {
    case KC_LCTL:
    case KC_RCTL:
      if (record->event.pressed) {
        isLunaSneaking = true;
      } else {
        isLunaSneaking = false;
      }
      break;
    case KC_SPC:
      if (record->event.pressed) {
        isLunaJumping = true;
        hasLunaJumped = false;
      } else {
        isLunaJumping = false;
      }
      break;
  }
  return true;
}
